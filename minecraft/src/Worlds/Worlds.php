<?php

declare(strict_types=1);

namespace OlivierDutoit\Minecraft\Worlds;

use InvalidArgumentException;
use OlivierDutoit\Minecraft\Players\World;
use OlivierDutoit\Minecraft\Server\MinecraftServer;
use OlivierDutoit\Minecraft\Server\Properties;
use Pterodactyl\Models\Server;

/**
 * The worlds in the server's folder: each folder with a level.dat. Bukkit-based servers keep the
 * Nether and the End in folders of their own (world_nether, world_the_end), shown with their world.
 */
final class Worlds
{
    public const string FOLDER = '/^[A-Za-z0-9][A-Za-z0-9_\-. ]{0,63}$/D';
    private const array DIMENSIONS = ['_nether', '_the_end'];

    public function __construct(
        private readonly MinecraftServer $files,
        private readonly World $world,
        private readonly WorldFiles $archives,
    ) {}

    /**
     * @return list<array<string, mixed>>
     */
    public function all(Server $server): array
    {
        $active = $this->files->world($server);
        $folders = [];
        foreach ($this->files->list($server, '/') as $entry) {
            $name = (string) ($entry['name'] ?? '');
            // Wings marks folders with file: false.
            if (($entry['file'] ?? true) === false && preg_match(self::FOLDER, $name)) {
                $folders[] = $name;
            }
        }

        $worlds = [];
        foreach ($folders as $folder) {
            if (self::dimensionOf($folder, $folders) !== null) {
                continue;
            }
            $info = $this->world->info($server, $folder, details: false);
            if (! $info['found'] && $folder !== $active) {
                continue;
            }

            $worlds[] = [
                'folder' => $folder,
                'folders' => $this->foldersOf($folder, $folders),
                'active' => $folder === $active,
                'found' => $info['found'],
                'name' => $info['name'] ?? $folder,
                'version' => $info['version'] ?? null,
                'seed' => $info['seed'] ?? null,
                'hardcore' => $info['hardcore'] ?? false,
                'gameMode' => $info['gameMode'] ?? null,
                'lastPlayed' => $info['lastPlayed'] ?? null,
            ];
        }

        usort($worlds, fn (array $a, array $b): int => [$b['active'], $b['lastPlayed'] ?? ''] <=> [$a['active'], $a['lastPlayed'] ?? '']);

        return $worlds;
    }

    /** The folders of a world: its own and its dimensions' that exist. */
    public function folders(Server $server, string $folder): array
    {
        self::assertFolder($folder);
        $all = [];
        foreach ($this->files->list($server, '/') as $entry) {
            if (($entry['file'] ?? true) === false) {
                $all[] = (string) ($entry['name'] ?? '');
            }
        }

        return $this->foldersOf($folder, $all);
    }

    /** Makes `$folder` the world the server loads at its next start. */
    public function activate(Server $server, string $folder): void
    {
        self::assertFolder($folder);
        $this->setProperties($server, ['level-name' => $folder]);
    }

    /** A new world, generated by the server at its next start. */
    public function create(Server $server, string $folder, ?string $seed, ?string $type): void
    {
        self::assertFolder($folder);
        foreach ($this->files->list($server, '/') as $entry) {
            if (strcasecmp((string) ($entry['name'] ?? ''), $folder) === 0) {
                throw new InvalidArgumentException("There is already a \"{$folder}\" in the server's folder.");
            }
        }
        if ($seed !== null && ! preg_match('/^-?[A-Za-z0-9_ ]{0,64}$/D', $seed)) {
            throw new InvalidArgumentException('A seed is a number or a word.');
        }
        if ($type !== null && ! preg_match('/^(?:[a-z0-9_.-]+:)?[a-z0-9_.\/-]{1,64}$/D', $type)) {
            throw new InvalidArgumentException('That is not a world type.');
        }

        $this->setProperties($server, array_filter(['level-name' => $folder, 'level-seed' => $seed ?? '', 'level-type' => $type], fn (?string $value): bool => $value !== null));
    }

    /** Deletes a world that is not the active one, with its dimensions' folders. */
    public function delete(Server $server, string $folder): void
    {
        $world = $this->find($server, $folder);
        if ($world['active']) {
            throw new InvalidArgumentException('The active world cannot be deleted: make another world active first.');
        }
        $this->archives->delete($server, '/', $world['folders']);
    }

    /**
     * One of the worlds the page lists: a folder with a level.dat (or the active world), never a
     * dimension folder on its own nor any other folder (plugins, mods…).
     *
     * @return array<string, mixed>
     */
    public function find(Server $server, string $folder): array
    {
        self::assertFolder($folder);
        foreach ($this->all($server) as $world) {
            if ($world['folder'] === $folder) {
                return $world;
            }
        }

        throw new InvalidArgumentException("\"{$folder}\" is not a world of this server.");
    }

    public static function assertFolder(string $folder): void
    {
        if (! preg_match(self::FOLDER, $folder) || str_contains($folder, '..')) {
            throw new InvalidArgumentException("\"{$folder}\" is not a world folder.");
        }
    }

    /** The world a dimension folder belongs to ("world" for "world_nether"), when that world exists. */
    private static function dimensionOf(string $folder, array $folders): ?string
    {
        foreach (self::DIMENSIONS as $suffix) {
            if (str_ends_with($folder, $suffix) && in_array(substr($folder, 0, -strlen($suffix)), $folders, true)) {
                return substr($folder, 0, -strlen($suffix));
            }
        }

        return null;
    }

    /** @return list<string> */
    private function foldersOf(string $folder, array $all): array
    {
        return array_values(array_filter([$folder, ...array_map(fn (string $suffix): string => $folder.$suffix, self::DIMENSIONS)], fn (string $name): bool => in_array($name, $all, true)));
    }

    /** @param array<string, string> $values */
    private function setProperties(Server $server, array $values): void
    {
        $properties = Properties::parse($this->files->readIfExists($server, MinecraftServer::PROPERTIES) ?? '');
        foreach ($values as $key => $value) {
            $properties->set($key, $value);
        }
        $this->files->write($server, MinecraftServer::PROPERTIES, $properties->contents());
    }
}
